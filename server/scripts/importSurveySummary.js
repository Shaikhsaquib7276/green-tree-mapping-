require('dotenv').config({path:require('node:path').join(__dirname,'..','.env')})
const mongoose=require('mongoose')
const connectDB=require('../config/db')
const CampusZone=require('../models/CampusZone')
const SurveySummary=require('../models/SurveySummary')
const summary={
 projectKey:'theem-campus-2026',
 surveyDate:new Date('2026-09-20T00:00:00.000Z'),
 totalTrees:38,
 zoneCounts:[{name:'Main Ground',count:10},{name:'Volleyball Ground',count:21},{name:'Parking',count:7},{name:'Flower Garden',count:0}],
 conditionCounts:{healthy:25,needsAttention:10,uncertain:3},
 speciesCounts:[{name:'Neem',count:2},{name:'Gulmohar',count:9},{name:'Ashoka',count:1},{name:'Bore (Ber)',count:2},{name:'Sitaphal',count:3},{name:'Amrud (Guava)',count:1},{name:'Jamun',count:2},{name:'Khajur',count:3},{name:'Black Jamun',count:4},{name:'White Jamun',count:2},{name:'Badam',count:2},{name:'Other / not identified',count:7}],
 verificationStatus:'verified',
 sourceNotes:'Aggregate field survey summary conducted at Theem College of Engineering, Betegaon on 20 September 2026. This is not a list of 38 individual tree records. Common names are field-recorded; scientific names and per-tree GPS coordinates are not asserted by this import.'
}
const zones=[
 {name:'Main Ground',slug:'main-ground',sortOrder:1,description:'Campus survey zone. Boundaries not mapped in this import.'},
 {name:'Volleyball Ground',slug:'volleyball-ground',sortOrder:2,description:'Campus survey zone. Boundaries not mapped in this import.'},
 {name:'Parking',slug:'parking',sortOrder:3,description:'Campus survey zone. Boundaries not mapped in this import.'},
 {name:'Flower Garden',slug:'flower-garden',sortOrder:4,description:'Campus survey zone. Boundaries not mapped in this import.'}
]
async function main(){
 if(summary.zoneCounts.reduce((n,z)=>n+z.count,0)!==summary.totalTrees)throw new Error('Zone counts do not add up to 38.')
 if(Object.values(summary.conditionCounts).reduce((n,v)=>n+v,0)!==summary.totalTrees)throw new Error('Condition counts do not add up to 38.')
 await connectDB()
 try{
  for(const zone of zones)await CampusZone.updateOne({slug:zone.slug},{$setOnInsert:{...zone,isActive:true}}, {upsert:true})
  const doc=await SurveySummary.findOneAndUpdate({projectKey:summary.projectKey},{$set:summary},{new:true,upsert:true,runValidators:true})
  const individualTreeRecords=await require('../models/Tree').countDocuments()
  console.log('Survey aggregate imported idempotently:',doc.projectKey,'totalTrees:',doc.totalTrees)
  console.log('Individual tree documents currently in database:',individualTreeRecords)
  console.log('No individual tree records or coordinates were generated by this script.')
 }finally{await mongoose.disconnect()}
}
main().catch(error=>{console.error('Survey import failed:',error.message);process.exitCode=1})